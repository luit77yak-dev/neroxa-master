#!/usr/bin/env python3
"""F02 21-case pre-gate EVIDENCE LEDGER, not 21 passing tests.
Never certifies consumer disablement, applies gate SQL, or reports release readiness.
Inputs are generated by the *actual* independent disposable buyer and pg_catalog steps.
"""
import argparse,collections,json,os,pathlib,subprocess
p=argparse.ArgumentParser()
p.add_argument('--buyer-log',required=True);p.add_argument('--catalog-json',required=True)
p.add_argument('--output',required=True);a=p.parse_args()
ids=[f'PG-{n:02d}' for n in range(1,10)]+[f'GT-{n:02d}' for n in range(1,4)]+[f'PO-{n:02d}' for n in range(1,10)]
assert len(ids)==21 and len(set(ids))==21
rows={id:dict(id=id,phase=id[:2],status='BLOCKED' if id.startswith('GT-') else 'NOT RUN',scope='NOT VERIFIED IN THIS RUN',evidence='no evidence obtained') for id in ids}
def record(id,status,scope,evidence):
 assert id in rows and status in ('PASS','FAIL','BLOCKED','NOT RUN')
 rows[id].update(status=status,scope=scope,evidence=evidence)
buyer=None; logpath=pathlib.Path(a.buyer_log)
if logpath.exists():
 for line in logpath.read_text(errors='replace').splitlines():
  pos=line.find('MISSION02A5_FINAL=')
  if pos>=0:
   try:buyer=json.loads(line[pos+len('MISSION02A5_FINAL='):])
   except json.JSONDecodeError: pass
catalog=None; catpath=pathlib.Path(a.catalog_json)
if catpath.exists():
 try:catalog=json.loads(catpath.read_text())
 except json.JSONDecodeError: pass
master=os.environ.get('GITHUB_SHA','')
try:delivery=subprocess.check_output(['git','-C','delivery-candidate','rev-parse','HEAD'],text=True,stderr=subprocess.DEVNULL).strip()
except (subprocess.CalledProcessError,FileNotFoundError):delivery=''
expectedDelivery='4ce88959a751066f96da4cbab8d1fc9ac29bb320'
if master and len(master)==40 and delivery==expectedDelivery:
 record('PG-01','PASS','SHAS FIXADOS PARA O RECORTE MASTER + FONTE DELIVERY','master='+master[:12]+'; delivery='+delivery[:12]+'; outros perfis não concatenados')
else:record('PG-01','BLOCKED','SOURCE IDENTITY NOT VERIFIED','master/delivery checkout missing or mismatched')
if catalog and catalog.get('kind')=='F02_PRE_GATE_PG_CATALOG_ONLY':
 signatures=[f.get('signature','') for f in catalog.get('functions',[])]
 record('PG-02','BLOCKED','CATALOGO MASTER READ-ONLY; DELIVERY COMPARADO EM RUN INDEPENDENTE','master_read_only='+str(len(signatures))+' functions; integrated SQL schema/overloads NOT VERIFIED')
else:record('PG-02','NOT RUN','NO CATALOG','PostgreSQL catalog result absent or invalid')
if buyer:
 checks=buyer.get('checks') or []
 def check(name,status='PASS'):
  return any(x.get('name')==name and x.get('status')==status for x in checks)
 samples=buyer.get('buyer') or []
 checkout=buyer.get('checkout') or {}
 positive=any(x.get('case')=='real HTTP A positive' and x.get('status')=='PASS' and x.get('http')==200 for x in samples)
 if check('F02 pre-gate direct phone RPC remains unresolved','FAIL') and (buyer.get('f02Observed') or {}).get('http')==200:
  record('PG-03','FAIL','F02 P0 CONFIRMADO EM CLONE PRE-GATE','anon UUID+phone returns 200; NOT A RELEASE PASS')
 else:record('PG-03','NOT RUN','F02 POSITIVE ATTACK EVIDENCE MISSING','No exact direct phone evidence')
 append=buyer.get('append') or {}
 attack=append.get('phoneAttack') or {}
 if attack.get('severity')=='P0' and attack.get('status')=='FAIL':
  record('PG-04','FAIL','P0 ANONYMOUS LEGACY APPEND MASTER PROFILE ONLY','HTTP='+str(attack.get('http'))+'; unauthorized return/mutation; before/after in F02_APPEND_PRE_GATE; Delivery enum NOT RUN')
 elif attack.get('status')=='PASS':
  record('PG-04','PASS','MASTER PHONE APPEND DENIAL ONLY; OTHER OVERLOADS NOT RUN','HTTP='+str(attack.get('http'))+'; full integrated coverage NOT VERIFIED')
 else:
  record('PG-04','NOT RUN','NO COMPLETED APPEND PROBE','No operation evidence; ACL alone is not mutation proof')
 if positive and str(checkout.get('status','')).startswith('PASS') and len(samples)>=11:
  record('PG-05','PASS','RECURSO COMPRADOR HTTP/ADAPTER; NAO TANSTACK E2E','checkout RPC token -> buyer HTTP 200, no PII; scoped')
  if all(x.get('status')=='PASS' for x in samples):
   record('PG-06','PASS','RECORTE 11 CENARIOS BUYER',str(len(samples))+' buyer tests PASS incl token denial, expiry/revoke/quota; verify detailed case logs')
 else:record('PG-05','NOT RUN','NO COMPLETE BUYER RECUT','HTTP+checkout scope not fully evidenced')
 if check('F01 candidate staff_none PATCH B') and check('F01 authorized own availability positive') and check('F01 own availability UPDATE positive'):
  record('PG-07','PASS','RECORTE A/B OWN AVAILABILITY / NO GRANT','negative staff B and positive admin B; broader integrated F01 still OPEN')
 else:record('PG-07','NOT RUN','F01 EVIDENCE INSUFFICIENT','Missing both positive and negative checks')
 record('PG-08','BLOCKED','BUYER DIGEST PARTIAL; NOT ALL TABLES/T1','Integrated before/after orders/items/payments/storage snapshots absent')
else:
 for id in ('PG-03','PG-04','PG-05','PG-06','PG-07','PG-08'):
  record(id,'NOT RUN','BUYER RUN DID NOT FINISH','missing MISSION02A5_FINAL')
record('PG-09','BLOCKED','CONSUMERS UNKNOWN','external installations and ten preview effective backends remain UNKNOWN')
for id in ('GT-01','GT-02','GT-03'):
 record(id,'BLOCKED','REAL CONSUMER GATE NOT SATISFIED','no CONSUMER-DISABLEMENT.json; no artificial GUC or REVOKE')
for id in [f'PO-{i:02d}' for i in range(1,10)]:
 record(id,'NOT RUN','GATE NOT APPLIED','post-gate evidence cannot exist in pre-gate run')
result=dict(scope='MASTER_DISPOSABLE_BUYER_PRE_GATE_WITH_PINNED_DELIVERY_SOURCE__NOT_INTEGRATED_RELEASE',source_master=master,source_delivery=delivery,case_count=21,gate='BLOCKED',post_gate='NOT RUN',f01='OPEN',f02='OPEN',marco01='0/7',commercial='NOT RELEASED',rows=[rows[id] for id in ids],counts=dict(collections.Counter(x['status'] for x in rows.values())))
pathlib.Path(a.output).write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
for r in result['rows']:
 print('F02_21_CASE='+json.dumps(r,sort_keys=True,ensure_ascii=False))
print('F02_21_SUMMARY='+json.dumps({k:v for k,v in result.items() if k!='rows'},sort_keys=True,ensure_ascii=False))
